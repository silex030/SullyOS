#!/usr/bin/env node
// node >= 20
//
// Builds every esbuild-bundled Worker in the WORKERS manifest. Dual-output:
//   worker/<name>/worker.bundle.js   ← user copies this into the CF dashboard
//   public/<outName>                 ← vite ships to dist/, Modal fetch reads it
//
// Adding a new Worker:
//   1. drop the entry at worker/<new>/src/index.ts
//   2. add a row to WORKERS below
//   3. that's it — `pnpm run build` (which chains to build:workers) picks it up
//
// Why a manifest array instead of auto-discover: some workers keep their
// runtime entry outside worker/<name>/src/index.ts (main-agent / heartbeat /
// wake-bridge bundles are verbatim copies; amsg's Deno facade goes through
// VERBATIM_COPIES). A naive scan would miss those. The manifest is explicit
// about which workers go through this pipeline.

import { build } from 'esbuild';
import { existsSync, statSync, readFileSync, writeFileSync, copyFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

// Each entry can override entry/outWorker/outPublic paths so we can bundle:
//   - per-worker dirs (worker/<name>/src/index.ts → worker/<name>/worker.bundle.js + public/<outName>)
//   - flat single-file workers (worker/<name>.ts → public/<name>.js only — no worker.bundle.js sibling)
const WORKERS = [
  { name: 'instant-push', outName: 'instant-worker.bundle.js' },
  // instant-push 的 Deno Deploy 入口: 同一份 worker, 换 Deno.serve 包装。
  // worker.deno.bundle.js 供整份贴进 dash.deno.com Playground;
  // public/ 副本让站点把它当静态文件发布, Playground 里一行
  // `import "https://<站点>/instant-worker.deno.bundle.js"` 即可加载运行。
  {
    name: 'instant-push-deno',
    entryPath: 'worker/instant-push/src/deno.ts',
    outWorker: 'worker/instant-push/worker.deno.bundle.js',
    outPublic: 'public/instant-worker.deno.bundle.js',
  },
  // sw-keep-alive 是 SullyOS 的 service worker, 唯一消费者是浏览器从 /public 静态读, 不需要
  // CF wrangler 单独部署 (没 worker.bundle.js sibling). 之前 bundle 是手工跑 esbuild, Round 2
  // 起接进 build:workers 一起做, 避免 worker/sw-keep-alive.ts 跟 public/sw-keep-alive.js 漂移.
  {
    name: 'sw-keep-alive',
    entryPath: 'worker/sw-keep-alive.ts',
    outPublic: 'public/sw-keep-alive.js',
    skipWorkerOut: true,
  },
  // post-office 是纯后端（跨用户漂流信），不被前端静态 fetch，所以只产 worker.bundle.js
  // 供粘进 CF 面板（选 ES Module 格式）或对照 wrangler deploy，不写 public/。
  {
    name: 'post-office',
    skipPublicOut: true,
  },
  // amsg = 主动消息 2.0 的单用户 worker（amsg-server/cloudflare, D1 + Cron Trigger）。
  // public/ 副本给设置页「复制 Worker 代码」按钮 fetch。amsg-server 2.6.0-next.2 起
  // 全 Web Crypto，和 instant 一样免 nodejs_compat flag。
  { name: 'amsg', outName: 'amsg-worker.bundle.js' },
  // proactive-push = 主动消息 1.0 的推送加速器（D1 + cron）。VPS 宿主加载
  // worker.bundle.js；此前 bundle 是 src 的手工合并版，2026-09-11 起改为
  // esbuild 产物，与其它走构建的 worker 同形态（避免 src 改了 bundle 忘了跟）。
  { name: 'proactive-push', skipPublicOut: true },
  // social-content = 链接分享解析（小红书/抖音/B站），独立 8842 服务，由 main-agent 反代。
  // 它是本清单里唯一用 node:* 的 worker（DNS 解析 + 连接绑定 transport 才能抗 DNS 重绑定），
  // 因此单独把 node:* 标成 external：宿主是 Node 22，不需要打进 bundle。
  {
    name: 'social-content',
    skipPublicOut: true,
    external: ['node:*'],
  },
  // sullyos-home = VPS Home 真相源（消息/记忆/事件/世界状态，8837）。纯后端，
  // 不被前端静态 fetch，只产 worker.bundle.js 供 VPS 宿主加载。
  { name: 'sullyos-home', skipPublicOut: true },
];

// amsg-instant 0.3.0+ uses only Web Crypto (globalThis.crypto.subtle); the
// bundle has zero Node crypto imports, so CF Workers / Vercel Edge / Netlify
// Edge run with no compatibility flags and no runtime polyfill.
const sharedOpts = {
  format: 'esm',
  target: 'es2022',
  platform: 'neutral',
  bundle: true,
  minify: false,
  conditions: ['worker', 'browser', 'import', 'default'],
  // cloudflare:* 是运行时自带的内置模块（amsg 用 cloudflare:workers 的 DurableObject
  // 基类）。它们不在 node_modules 里，不标 external 的话 esbuild 会当成缺失依赖报错。
  external: ['cloudflare:*'],
};

// esbuild 给内联模块打的 `// <相对路径>` 头注释是按 cwd 解析的。本仓 node_modules 在
// 多 worktree 下是指向主检出的符号链接（/root/SullyOS-travel/node_modules →
// /root/SullyOS/node_modules），同一份源码会产出 `../SullyOS/node_modules/…` 与
// `node_modules/…` 两种头注释 —— 产物哈希随检出目录变化，check:workers 换 worktree 就假红。
// 统一裁到 `node_modules/` 起，产物与检出位置无关。
function normalizeModuleBannerComments(file) {
  const text = readFileSync(file, 'utf8');
  const normalized = text.replace(/^\/\/ .*?(node_modules\/)/gm, '// $1');
  if (normalized !== text) writeFileSync(file, normalized);
}

console.log(`Building ${WORKERS.length} worker bundle(s)...`);

for (const w of WORKERS) {
  const entry = resolve(root, w.entryPath || `worker/${w.name}/src/index.ts`);
  if (!existsSync(entry)) {
    console.error(`ERROR: entry not found for "${w.name}": ${entry}`);
    process.exit(1);
  }

  const banner = { js: `/* generated by scripts/build-workers.mjs — do not edit by hand */` };
  const outputs = [];

  let outWorker = null;
  if (!w.skipWorkerOut) {
    outWorker = resolve(root, w.outWorker || `worker/${w.name}/worker.bundle.js`);
    outputs.push(outWorker);
  }
  let outPublic = null;
  if (!w.skipPublicOut) {
    outPublic = resolve(root, w.outPublic || `public/${w.outName}`);
    outputs.push(outPublic);
  }
  if (outputs.length === 0) {
    console.error(`ERROR: "${w.name}" skips both worker and public output — nothing to build`);
    process.exit(1);
  }

  for (const out of outputs) {
    await build({
      ...sharedOpts,
      ...(w.external ? { external: [...sharedOpts.external, ...w.external] } : {}),
      entryPoints: [entry],
      outfile: out,
      banner,
    });
    normalizeModuleBannerComments(out);
  }

  const sizeRef = outWorker || outPublic;
  const sizeKb = (statSync(sizeRef).size / 1024).toFixed(1);
  const dest = [
    outWorker && (w.outWorker || `worker/${w.name}/worker.bundle.js`),
    outPublic && (w.outPublic || `public/${w.outName}`),
  ].filter(Boolean).join(' + ');
  console.log(`✓ ${w.name.padEnd(16)} ${sizeKb} KB  → ${dest}`);
}

// 原样复制到 public/ 的单文件脚本（不过 esbuild）。
//
// 为什么不打包：这些文件没有 import，是自包含单文件，而 Deno Playground 原生吃
// TypeScript。过一遍 esbuild 只会剥掉类型、还可能顺手把注释吃了 —— 而这类脚本
// 恰恰要用户读着注释改配置（比如 amsg 代理里的 UPSTREAM 那一行），注释没了就废了。
const VERBATIM_COPIES = [
  // amsg 的 Deno 门面：给 Cloudflare worker 换一个国内能直连的地址。
  // 设置页「复制 Deno 代理代码」按钮 fetch 这份。
  { from: 'worker/amsg/deno-proxy.ts', to: 'public/amsg-deno-proxy.ts' },
  // 注意：main-agent 不在这个列表里 —— 它有一个相对 import，见下面 buildMainAgentBundle。
  { from: 'worker/heartbeat/src/index.js', to: 'worker/heartbeat/worker.bundle.js' },
  { from: 'worker/wake-bridge/src/index.js', to: 'worker/wake-bridge/worker.bundle.js' },
];

// ── main-agent：自包含 bundle（内联 local-embedding 路由）──────────────
//
// 为什么不像以前那样 `cp src/index.js worker.bundle.js`：
// VPS 的加载器是 `vps-backend/src/shim/bundle-loader.js`，它把整份源码塞进
// `data:text/javascript;base64,…` 再 `import()`。data: URL **没有 base**，bundle 里
// 任何相对 import 都会 ERR_UNSUPPORTED_RESOLVE_REQUEST（实测线上 8830 起不来、
// Caddy 全 502）。所以 bundle 必须自包含：把 src/local-embedding-route.js 内联进来，
// 并剥掉 index.js 里那一行 import。src/ 侧保持正常模块（测试与类型仍 import 真模块）。
//
// 内联体包在 IIFE 里，避免与 index.js 的同名工具函数（json / CORS_HEADERS / num …）冲突。
const MAIN_AGENT_ROUTE = 'worker/main-agent/src/local-embedding-route.js';
const MAIN_AGENT_ENTRY = 'worker/main-agent/src/index.js';
const MAIN_AGENT_BUNDLE = 'worker/main-agent/worker.bundle.js';
const MAIN_AGENT_IMPORT_LINE = "import { handleLocalEmbedding } from './local-embedding-route.js';";

function buildMainAgentBundle() {
  const routeSrc = readFileSync(resolve(root, MAIN_AGENT_ROUTE), 'utf8');
  const indexSrc = readFileSync(resolve(root, MAIN_AGENT_ENTRY), 'utf8');

  // 前置校验：路由模块必须自包含，否则内联不成立，直接失败而不是产出坏 bundle。
  if (/^\s*import\s/m.test(routeSrc)) {
    console.error(`ERROR: ${MAIN_AGENT_ROUTE} 不能再有 import（内联进 bundle 时无处解析）`);
    process.exit(1);
  }
  if (!indexSrc.includes(MAIN_AGENT_IMPORT_LINE)) {
    console.error(`ERROR: ${MAIN_AGENT_ENTRY} 缺少预期的 local-embedding import 行，构建脚本需要同步更新`);
    process.exit(1);
  }

  const routeBody = routeSrc
    .replace(/^export\s+(?=(?:async\s+)?function|const|let|class|default)/gm, '');
  if (/\bexport\b/.test(routeBody)) {
    console.error(`ERROR: ${MAIN_AGENT_ROUTE} 仍有未处理的 export，内联会产出语法错误`);
    process.exit(1);
  }
  if (!/function\s+handleLocalEmbedding|const\s+handleLocalEmbedding/.test(routeBody)) {
    console.error(`ERROR: ${MAIN_AGENT_ROUTE} 没有 handleLocalEmbedding，内联约定已变`);
    process.exit(1);
  }

  const inlined = [
    '// [build-workers] 内联自 src/local-embedding-route.js —— VPS 用 data: URL 加载，',
    '// 相对 import 无 base 可解析，所以路由必须与入口同一个文件。改路由请改 src/ 那份。',
    'const { handleLocalEmbedding } = (() => {',
    routeBody.trimEnd(),
    '  return { handleLocalEmbedding };',
    '})();',
    '',
    indexSrc.replace(MAIN_AGENT_IMPORT_LINE + '\n', ''),
  ].join('\n');

  writeFileSync(resolve(root, MAIN_AGENT_BUNDLE), inlined);
  const kb = (statSync(resolve(root, MAIN_AGENT_BUNDLE)).size / 1024).toFixed(1);
  console.log(`✓ ${'main-agent'.padEnd(16)} ${kb} KB  → ${MAIN_AGENT_BUNDLE} (内联 local-embedding 路由)`);
}

buildMainAgentBundle();

for (const { from, to } of VERBATIM_COPIES) {
  const src = resolve(root, from);
  if (!existsSync(src)) {
    console.error(`ERROR: verbatim copy source not found: ${from}`);
    process.exit(1);
  }
  copyFileSync(src, resolve(root, to));
  const sizeKb = (statSync(src).size / 1024).toFixed(1);
  console.log(`✓ ${from.split('/').pop().padEnd(16)} ${sizeKb} KB  → ${to} (原样复制)`);
}

// instant-worker.version.txt — Deno loader 冷启动时拉这个文件决定 bundle 版本号
// (见 utils/instantPushClient.ts 的 buildDenoLoaderSnippet)。从
// utils/instantWorkerVersion.ts 提取, 与 /version 路由同源, 不会漂移。
const versionSrc = readFileSync(resolve(root, 'utils/instantWorkerVersion.ts'), 'utf8');
const versionMatch = versionSrc.match(/INSTANT_WORKER_VERSION\s*=\s*'([^']+)'/);
if (!versionMatch) {
  console.error('ERROR: cannot extract INSTANT_WORKER_VERSION from utils/instantWorkerVersion.ts');
  process.exit(1);
}
writeFileSync(resolve(root, 'public/instant-worker.version.txt'), `${versionMatch[1]}\n`);
console.log(`✓ instant-worker.version.txt → ${versionMatch[1]}`);
